export function getTodaysHero() {
    const now = new Date();
    const utc8Date = new Date(now.toLocaleString('en-US', { timeZone: 'America/Los_Angeles' }));
    const currentDateStr = `${utc8Date.getMonth() + 1}/${utc8Date.getDate()}/${utc8Date.getFullYear() % 100}`;

    const findHeroForDate = (date) => {
        const hero = dailyHeroesList.find(item => item[date]);
        return hero ? hero[date] : null;
    };

    const getYesterdayDateStr = (dateStr) => {
        const currentDate = new Date(dateStr.replace(/\//g, '-'));
        const yesterdayDate = new Date(currentDate.setDate(currentDate.getDate() - 1));
        return `${yesterdayDate.getMonth() + 1}/${yesterdayDate.getDate()}/${yesterdayDate.getFullYear() % 100}`;
    };

    if (utc8Date.getHours() >= 12) {
        return findHeroForDate(currentDateStr);
    } else {
        const yesterdayDateStr = getYesterdayDateStr(currentDateStr);
        return findHeroForDate(yesterdayDateStr);
    }
}
